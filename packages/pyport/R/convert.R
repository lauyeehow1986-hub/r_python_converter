# Standalone R package generator (`pyport::convert()`).
#
# Converts a Python package directory, `.tar.gz` sdist, `.whl` wheel, or single
# `.py` module into a standalone, CRAN-clean R package that depends only on
# `pyrt` and `gmp`.

write_lf <- function(lines, path) {
  dir.create(dirname(path), recursive = TRUE, showWarnings = FALSE)
  con <- file(path, open = "wb")
  on.exit(close(con), add = TRUE)
  writeLines(enc2utf8(as.character(lines)), con = con, sep = "\n", useBytes = TRUE)
  invisible(path)
}

#' Sanitize a Python package name into a valid CRAN R package name
#'
#' Replaces hyphens and underscores with dots, strips invalid characters, and
#' ensures the name starts with an ASCII letter and does not end with a dot.
#'
#' @param name Character string (e.g. `"more-itertools"`, `"python_dateutil"`).
#' @returns A valid R package name string (e.g. `"more.itertools"`).
#' @export
#' @examples
#' sanitize_r_pkg_name("more-itertools")
#' sanitize_r_pkg_name("python_dateutil")
sanitize_r_pkg_name <- function(name) {
  out <- gsub("[-_]+", ".", trimws(name))
  out <- gsub("[^A-Za-z0-9.]", "", out)
  out <- gsub("\\.+", ".", out)
  out <- sub("^\\.+", "", out)
  out <- sub("\\.+$", "", out)
  if (!nzchar(out) || !grepl("^[A-Za-z]", out)) {
    out <- paste0("py.", out)
  }
  if (nchar(out) < 2L) {
    out <- paste0(out, "pkg")
  }
  out
}

sanitize_r_version <- function(ver) {
  if (is.null(ver) || !nzchar(trimws(ver))) return("0.1.0")
  m <- regmatches(ver, regexpr("[0-9]+(\\.[0-9]+)+", ver))
  if (length(m) == 1L && nzchar(m)) m else "0.1.0"
}

read_python_metadata <- function(src_dir, default_name = "pypkg") {
  meta <- list(
    name = default_name,
    version = "0.1.0",
    summary = sprintf("Converted from the '%s' Python Package", default_name),
    description = sprintf(
      "Standalone native 'R' port of the '%s' 'Python' package generated by 'pyport'. Runs natively in 'R' via 'pyrt' without requiring a 'Python' installation.",
      default_name
    ),
    author = sprintf("%s authors", default_name),
    license = "MIT"
  )

  pyproject <- file.path(src_dir, "pyproject.toml")
  if (file.exists(pyproject)) {
    txt <- paste(readLines(pyproject, warn = FALSE, encoding = "UTF-8"), collapse = "\n")
    extract_toml <- function(key) {
      pat <- paste0("(?m)^\\s*", key, "\\s*=\\s*[\"']([^\"'\r\n]+)[\"']")
      m <- regmatches(txt, regexec(pat, txt, perl = TRUE))[[1L]]
      if (length(m) >= 2L) m[[2L]] else NULL
    }
    if (!is.null(nm <- extract_toml("name"))) meta$name <- nm
    if (!is.null(vr <- extract_toml("version"))) meta$version <- vr
    if (!is.null(desc <- extract_toml("description"))) meta$summary <- desc
    if (!is.null(lic <- extract_toml("license"))) {
      meta$license <- lic
    } else {
      # Check `license = { text = "..." }` or `{ file = "..." }`
      m_lic <- regmatches(txt, regexec("license\\s*=\\s*\\{[^}]*text\\s*=\\s*[\"']([^\"']+)[\"']", txt, perl = TRUE))[[1L]]
      if (length(m_lic) >= 2L) meta$license <- m_lic[[2L]]
    }
  }

  setup_cfg <- file.path(src_dir, "setup.cfg")
  if (file.exists(setup_cfg)) {
    lines <- readLines(setup_cfg, warn = FALSE, encoding = "UTF-8")
    for (ln in lines) {
      if (grepl("^\\s*name\\s*=", ln)) meta$name <- trimws(sub("^\\s*name\\s*=\\s*", "", ln))
      if (grepl("^\\s*version\\s*=", ln)) {
        v_cand <- trimws(sub("^\\s*version\\s*=\\s*", "", ln))
        if (grepl("^[0-9]", v_cand)) meta$version <- v_cand
      }
      if (grepl("^\\s*description\\s*=", ln)) meta$summary <- trimws(sub("^\\s*description\\s*=\\s*", "", ln))
      if (grepl("^\\s*license\\s*=", ln)) meta$license <- trimws(sub("^\\s*license\\s*=\\s*", "", ln))
    }
  }

  pkg_info <- file.path(src_dir, "PKG-INFO")
  if (file.exists(pkg_info)) {
    lines <- readLines(pkg_info, warn = FALSE, encoding = "UTF-8")
    for (ln in lines) {
      if (startsWith(ln, "Name:")) meta$name <- trimws( substring(ln, 6L))
      if (startsWith(ln, "Version:")) meta$version <- trimws(substring(ln, 9L))
      if (startsWith(ln, "Summary:")) meta$summary <- trimws(substring(ln, 9L))
      if (startsWith(ln, "License:")) meta$license <- trimws(substring(ln, 9L))
    }
  }

  meta
}

discover_python_modules <- function(src_dir) {
  # Look for `src/<pkg>/*.py`, `<pkg>/*.py`, or top-level `*.py`
  all_py <- list.files(src_dir, pattern = "\\.py$", recursive = TRUE, full.names = TRUE)
  rel <- substring(normalizePath(all_py, winslash = "/"),
                   nchar(normalizePath(src_dir, winslash = "/")) + 2L)

  is_test_or_setup <- grepl("(^|/)(tests?|testing|docs?|examples?|benchmarks?)/", rel) |
                      grepl("(^|/)(setup|conftest|test_.*|.*_test)\\.py$", rel)
  mod_files <- all_py[!is_test_or_setup]
  mod_rel <- rel[!is_test_or_setup]

  # Order submodules before `__init__.py` so helpers exist when `__init__.py`
  # re-exports them.
  is_init <- grepl("(^|/)__init__\\.py$", mod_rel)
  ord <- order(is_init, mod_rel)
  list(
    files = mod_files[ord],
    rel = mod_rel[ord],
    test_files = all_py[grepl("(^|/)test_[^/]+\\.py$", rel)]
  )
}

extract_module_exports <- function(tree) {
  # If `__all__ = [...]` is assigned at top level, respect it; otherwise export
  # all public top-level FunctionDef, ClassDef, and Assign Name targets (not
  # starting with `_`).
  explicit_all <- NULL
  public <- character()

  for (st in tree$body) {
    if (st$kind %in% c("FunctionDef", "AsyncFunctionDef", "ClassDef")) {
      if (!startsWith(st$name, "_")) public <- c(public, st$name)
    } else if (st$kind == "Assign") {
      for (t in st$targets) {
        if (is_py_ast(t, "Name")) {
          if (identical(t$id, "__all__") && is_py_ast(st$value, c("List", "Tuple"))) {
            elts <- st$value$elts
            strs <- unlist(lapply(elts, function(e) {
              if (is_py_ast(e, "Constant") && identical(e$ctype, "str")) e$value else NULL
            }))
            explicit_all <- c(explicit_all, strs)
          } else if (!startsWith(t$id, "_")) {
            public <- c(public, t$id)
          }
        }
      }
    }
  }

  if (!is.null(explicit_all)) unique(explicit_all) else unique(public)
}

generate_rd_for_package <- function(r_pkg_name, title, description, exports, envir) {
  # Build a clean package-level Rd file and one Rd file per exported symbol
  # whose `\usage` and `\arguments` match the actual R object in `envir`.
  rd_list <- list()

  escape_rd <- function(s) {
    s <- gsub("\\", "\\\\", s, fixed = TRUE)
    s <- gsub("{", "\\{", s, fixed = TRUE)
    s <- gsub("}", "\\}", s, fixed = TRUE)
    s <- gsub("%", "\\%", s, fixed = TRUE)
    s
  }

  pkg_rd <- c(
    sprintf("\\name{%s-package}", r_pkg_name),
    sprintf("\\alias{%s-package}", r_pkg_name),
    sprintf("\\title{%s}", escape_rd(title)),
    "\\description{",
    sprintf("  %s", escape_rd(description)),
    "}",
    "\\keyword{internal}"
  )
  rd_list[[paste0(r_pkg_name, "-package.Rd")]] <- pkg_rd

  for (sym in exports) {
    if (!exists(sym, envir = envir, inherits = FALSE)) next
    obj <- get(sym, envir = envir, inherits = FALSE)
    safe_file <- paste0("py_", gsub("[^A-Za-z0-9_]", "_", sym), ".Rd")

    if (is.function(obj) && !inherits(obj, "pyrt_class")) {
      fmls <- formals(obj)
      fml_names <- names(fmls)
      usage_args <- character()
      for (i in seq_along(fmls)) {
        fn_i <- r_ident(fml_names[[i]])
        def_i <- fmls[[i]]
        if (missing(def_i) || (is.symbol(def_i) && identical(as.character(def_i), ""))) {
          usage_args <- c(usage_args, fn_i)
        } else {
          dep <- paste(deparse(def_i, width.cutoff = 500L), collapse = " ")
          usage_args <- c(usage_args, paste0(fn_i, " = ", dep))
        }
      }
      usage_str <- sprintf("%s(%s)", r_ident(sym), paste(usage_args, collapse = ", "))
      arg_items <- vapply(fml_names, function(nm) {
        sprintf("  \\item{%s}{Argument passed to \\code{%s}.}", escape_rd(nm), escape_rd(sym))
      }, character(1))

      rd_lines <- c(
        sprintf("\\name{%s}", escape_rd(sym)),
        sprintf("\\alias{%s}", escape_rd(sym)),
        sprintf("\\title{Function \\code{%s}}", escape_rd(sym)),
        "\\description{",
        sprintf("  Transpiled Python function \\code{%s}.", escape_rd(sym)),
        "}",
        "\\usage{",
        escape_rd(usage_str),
        "}",
        if (length(arg_items) > 0L) c("\\arguments{", arg_items, "}") else NULL,
        "\\value{",
        "  Result of the transpiled Python function.",
        "}"
      )
      rd_list[[safe_file]] <- rd_lines
    } else {
      rd_lines <- c(
        sprintf("\\name{%s}", escape_rd(sym)),
        sprintf("\\alias{%s}", escape_rd(sym)),
        sprintf("\\docType{data}"),
        sprintf("\\title{Object \\code{%s}}", escape_rd(sym)),
        "\\description{",
        sprintf("  Transpiled Python class or module binding \\code{%s}.", escape_rd(sym)),
        "}",
        "\\keyword{datasets}"
      )
      rd_list[[safe_file]] <- rd_lines
    }
  }

  rd_list
}

#' Convert a Python package or module into a standalone R package
#'
#' Parses a Python package directory (or `.tar.gz` sdist, `.whl` wheel, or
#' single `.py` file), audits its license via [check_python_license()],
#' transpiles all Python modules into R code backed by `pyrt`, translates
#' discovered `pytest`/`unittest` tests into `testthat` tests, and writes a
#' complete, CRAN-ready R package to `dest`.
#'
#' @param source Path to a Python package directory, `.tar.gz` / `.whl` archive,
#'   or single `.py` file.
#' @param dest Output directory where the generated R package will be written.
#' @param pkg_name Optional explicit R package name (defaults to sanitized
#'   Python package/module name).
#' @param overwrite Logical; if `TRUE` (the default), overwrites `dest` if it
#'   already exists.
#' @returns Invisibly returns a list summarizing the generated R package
#'   (`pkg_name`, `path`, `exports`, `license`, `modules`, `diagnostics`).
#' @export
#' @examples
#' tmp_py <- tempfile(fileext = ".py")
#' writeLines(c(
#'   "def clamp(x, lo=0, hi=10):",
#'   "    return max(lo, min(hi, x))"
#' ), tmp_py)
#' out_dir <- file.path(tempdir(), "clmapr")
#' convert(tmp_py, out_dir, pkg_name = "clampr")
convert <- function(source, dest, pkg_name = NULL, overwrite = TRUE) {
  if (!file.exists(source)) {
    stop(sprintf("`source` path does not exist: '%s'", source))
  }

  work_dir <- NULL
  on.exit({
    if (!is.null(work_dir) && dir.exists(work_dir)) {
      unlink(work_dir, recursive = TRUE)
    }
  }, add = TRUE)

  if (!dir.exists(source)) {
    if (grepl("\\.py$", source, ignore.case = TRUE)) {
      work_dir <- tempfile("pyport_src_")
      dir.create(work_dir, recursive = TRUE)
      file.copy(source, file.path(work_dir, basename(source)))
      src_dir <- work_dir
      default_name <- tools::file_path_sans_ext(basename(source))
    } else if (grepl("\\.(tar\\.gz|tgz)$", source, ignore.case = TRUE)) {
      work_dir <- tempfile("pyport_sdist_")
      dir.create(work_dir, recursive = TRUE)
      utils::untar(source, exdir = work_dir)
      subdirs <- list.dirs(work_dir, recursive = FALSE, full.names = TRUE)
      src_dir <- if (length(subdirs) == 1L) subdirs[[1L]] else work_dir
      default_name <- sub("-[0-9].*$", "", basename(src_dir))
    } else if (grepl("\\.(whl|zip)$", source, ignore.case = TRUE)) {
      work_dir <- tempfile("pyport_whl_")
      dir.create(work_dir, recursive = TRUE)
      utils::unzip(source, exdir = work_dir)
      src_dir <- work_dir
      default_name <- sub("-[0-9].*$", "", basename(source))
    } else {
      stop("Unsupported `source` file format; expected directory, `.py`, `.tar.gz`, or `.whl`.")
    }
  } else {
    src_dir <- source
    default_name <- basename(normalizePath(source, winslash = "/"))
  }

  meta <- read_python_metadata(src_dir, default_name = default_name)
  lic_info <- check_python_license(meta$license)
  r_pkg <- sanitize_r_pkg_name(if (!is.null(pkg_name)) pkg_name else meta$name)
  r_ver <- sanitize_r_version(meta$version)

  discovered <- discover_python_modules(src_dir)
  native_ext <- detect_native_extensions(src_dir)
  if (length(discovered$files) == 0L && !native_ext$has_c && !native_ext$has_rust) {
    stop(sprintf("No Python modules (`.py`) or native extensions found in '%s'.", source))
  }

  if (dir.exists(dest)) {
    if (!isTRUE(overwrite)) {
      stop(sprintf("Destination '%s' already exists and `overwrite = FALSE`.", dest))
    }
    unlink(dest, recursive = TRUE)
  }
  dir.create(file.path(dest, "R"), recursive = TRUE, showWarnings = FALSE)
  dir.create(file.path(dest, "man"), recursive = TRUE, showWarnings = FALSE)

  # Transpile all discovered modules and evaluate them in a sandbox environment
  # so we can inspect exported objects and build exact `.Rd` documentation.
  eval_env <- new.env(parent = globalenv())
  eval_env$.py_mod_env <- eval_env

  all_exports <- character()
  all_globals <- c(".py_mod_env", ".py_gen_env")
  all_diags <- list()
  r_files <- "00-pyport-env.R"
  has_dynlib <- FALSE

  for (i in seq_along(discovered$files)) {
    py_path <- discovered$files[[i]]
    rel_i <- discovered$rel[[i]]
    py_txt <- paste(readLines(py_path, warn = FALSE, encoding = "UTF-8"), collapse = "\n")
    tree_i <- parse_python(py_txt)

    # Strip intra-package relative imports (`from .mod import x`) since all
    # modules in the generated R package share the package namespace!
    tree_i$body <- Filter(function(st) {
      !(st$kind == "ImportFrom" && !is.null(st$level) && st$level >= 1L)
    }, tree_i$body)

    r_code <- transpile_python(tree_i, module_name = rel_i)
    info_i <- attr(r_code, "analysis")
    all_diags <- c(all_diags, info_i$diagnostics)
    all_globals <- unique(c(all_globals, collect_all_scope_vars(info_i$scope)))
    all_exports <- unique(c(all_exports, extract_module_exports(tree_i)))

    r_fname <- sprintf("%02d-%s.R", i, gsub("[^A-Za-z0-9_]", "_", tools::file_path_sans_ext(rel_i)))
    r_files <- c(r_files, r_fname)
    write_lf(as.character(r_code), file.path(dest, "R", r_fname))

    exprs <- parse(text = as.character(r_code), keep.source = FALSE)
    eval(exprs, envir = eval_env)
  }

  # Bridge C extensions if present
  if (native_ext$has_c) {
    dir.create(file.path(dest, "src"), recursive = TRUE, showWarnings = FALSE)
    write_lf(cpython_shim_header(), file.path(dest, "src", "pyport_cpython_shim.h"))
    c_srcs <- lapply(native_ext$c_files, function(cf) {
      paste(readLines(file.path(src_dir, cf), warn = FALSE, encoding = "UTF-8"), collapse = "\n")
    })
    bridged <- transpile_c_extension(paste(c_srcs, collapse = "\n\n"), pkg_name = r_pkg)
    if (length(bridged$functions) > 0L) {
      has_dynlib <- TRUE
      write_lf(bridged$c_code, file.path(dest, "src", "native_ext.c"))
      write_lf(bridged$r_code, file.path(dest, "R", "90-native-bridge.R"))
      r_files <- c(r_files, "90-native-bridge.R")
      eval(parse(text = bridged$r_code, keep.source = FALSE), envir = eval_env)
      all_exports <- unique(c(all_exports, bridged$functions))
    }
  }

  # Keep only exports that actually exist in `eval_env` and are valid identifiers.
  all_exports <- Filter(function(sym) {
    exists(sym, envir = eval_env, inherits = FALSE) &&
      !(sym %in% r_reserved_words) &&
      grepl("^[A-Za-z][A-Za-z0-9._]*$", sym)
  }, all_exports)

  # Write `R/00-pyport-env.R` initializing `.py_mod_env` and registering
  # `utils::globalVariables` so `R CMD check` (`codetools`) emits 0 notes.
  gv_quoted <- paste(vapply(unique(all_globals), deparse_r_str, character(1)), collapse = ", ")
  env_lines <- c(
    "# Generated by pyport: module environment and codetools declarations",
    ".py_mod_env <- environment()",
    sprintf("utils::globalVariables(c(%s))", gv_quoted)
  )
  write_lf(env_lines, file.path(dest, "R", "00-pyport-env.R"))

  # Write `DESCRIPTION`
  clean_title <- gsub("[\r\n]+", " ", meta$summary)
  clean_title <- sub("\\.+$", "", trimws(clean_title))
  if (!nzchar(clean_title)) clean_title <- sprintf("Converted '%s' Package", meta$name)

  desc_lines <- c(
    sprintf("Package: %s", r_pkg),
    sprintf("Title: %s", clean_title),
    sprintf("Version: %s", r_ver),
    sprintf("Authors@R: person(%s, role = c(\"aut\", \"cre\"), email = \"maintainer@example.com\")",
            deparse_r_str(meta$author)),
    sprintf("Description: %s", meta$description),
    sprintf("License: %s", lic_info$cran_license),
    "Encoding: UTF-8",
    "Depends: R (>= 4.3.0)",
    "Imports:",
    "    gmp (>= 0.7-1),",
    "    pyrt (>= 0.0.0.9000),",
    "    utils",
    "Suggests:",
    "    testthat (>= 3.0.0)",
    sprintf("Collate: %s", paste(sprintf("'%s'", r_files), collapse = " ")),
    "Config/testthat/edition: 3"
  )
  write_lf(desc_lines, file.path(dest, "DESCRIPTION"))

  if (isTRUE(lic_info$needs_license_file)) {
    lic_lines <- c(
      sprintf("YEAR: %s", format(Sys.Date(), "%Y")),
      sprintf("COPYRIGHT HOLDER: %s", meta$author)
    )
    write_lf(lic_lines, file.path(dest, "LICENSE"))
  }

  # Write `NAMESPACE`
  ns_lines <- c(
    "# Generated by pyport: do not edit by hand",
    if (has_dynlib) sprintf("useDynLib(%s, .registration = TRUE)", r_pkg) else NULL,
    "import(pyrt)",
    "importFrom(gmp, as.bigz)",
    "importFrom(utils, globalVariables)",
    if (length(all_exports) > 0L) sprintf("export(%s)", all_exports) else NULL
  )
  write_lf(ns_lines, file.path(dest, "NAMESPACE"))

  # Write `man/*.Rd`
  rd_files <- generate_rd_for_package(r_pkg, clean_title, meta$description, all_exports, eval_env)
  for (rd_name in names(rd_files)) {
    write_lf(rd_files[[rd_name]], file.path(dest, "man", rd_name))
  }

  # Convert discovered pytest/unittest files (or emit a smoke test)
  dir.create(file.path(dest, "tests", "testthat"), recursive = TRUE, showWarnings = FALSE)
  write_lf(
    c(
      "library(testthat)",
      sprintf("library(%s)", r_pkg),
      "",
      sprintf("test_check(\"%s\")", r_pkg)
    ),
    file.path(dest, "tests", "testthat.R")
  )

  if (length(discovered$test_files) > 0L) {
    for (tf in discovered$test_files) {
      py_test_src <- paste(readLines(tf, warn = FALSE, encoding = "UTF-8"), collapse = "\n")
      r_test_code <- convert_pytest_code(py_test_src, pkg_name = meta$name)
      out_tname <- paste0(
        "test-",
        gsub("[^A-Za-z0-9_]", "-", sub("^test_", "", tools::file_path_sans_ext(basename(tf)))),
        ".R"
      )
      write_lf(r_test_code, file.path(dest, "tests", "testthat", out_tname))
    }
  } else {
    write_lf(
      c(
        sprintf("test_that(\"%s loads cleanly\", {", r_pkg),
        sprintf("  expect_true(isNamespaceLoaded(\"%s\"))", r_pkg),
        "})"
      ),
      file.path(dest, "tests", "testthat", "test-smoke.R")
    )
  }

  invisible(list(
    pkg_name = r_pkg,
    version = r_ver,
    path = dest,
    exports = all_exports,
    license = lic_info,
    modules = discovered$rel,
    diagnostics = all_diags
  ))
}

collect_all_scope_vars <- function(scope) {
  vars <- c(scope$locals, scope$params, scope$globals, scope$nonlocals)
  for (ch in scope$children) {
    vars <- c(vars, collect_all_scope_vars(ch))
  }
  unique(vars)
}
