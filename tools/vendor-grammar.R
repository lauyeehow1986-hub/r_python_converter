# Vendor the tree-sitter-python grammar into packages/pyport/src.
#
# Dev-only script (needs network). Run from the repo root:
#   Rscript tools/vendor-grammar.R [version]
#
# The grammar's ABI must be supported by the tree-sitter core bundled in the
# CRAN `treesitter` package (treesitter 0.3.x bundles tree-sitter 0.24.x, which
# supports ABI 13-14). tree-sitter-python 0.23.6 is generated with ABI 14.

args <- commandArgs(trailingOnly = TRUE)
version <- if (length(args) >= 1) args[[1]] else "0.23.6"

# Always write LF line endings (text-mode connections give CRLF on Windows).
write_lf <- function(lines, path) {
  con <- file(path, open = "wb")
  on.exit(close(con))
  writeLines(lines, con, sep = "\n", useBytes = TRUE)
}

root <- normalizePath(".", winslash = "/")
pkg_src <- file.path(root, "packages", "pyport", "src")
if (!dir.exists(pkg_src)) {
  stop("Run from the repository root (packages/pyport/src not found).")
}

tmp <- tempfile("tsp")
dir.create(tmp)
url <- sprintf(
  "https://github.com/tree-sitter/tree-sitter-python/archive/refs/tags/v%s.tar.gz",
  version
)
tarball <- file.path(tmp, "tsp.tar.gz")
utils::download.file(url, tarball, mode = "wb", quiet = TRUE)
utils::untar(tarball, exdir = tmp)
src <- file.path(tmp, sprintf("tree-sitter-python-%s", version), "src")

dir.create(file.path(pkg_src, "tree_sitter"), showWarnings = FALSE)
files <- c(
  "parser.c", "scanner.c",
  "tree_sitter/parser.h", "tree_sitter/array.h", "tree_sitter/alloc.h"
)
for (f in files) {
  lines <- readLines(file.path(src, f), warn = FALSE)
  # R CMD check flags `#pragma` lines that suppress diagnostics; the CRAN
  # tree-sitter grammar packages use the equivalent `# pragma` spelling.
  lines <- sub("^#pragma ", "# pragma ", lines)
  # `array_pop()` used as a statement triggers -Wunused-value, which
  # R CMD check reports; cast to void (no behaviour change).
  lines <- sub("^(\\s*)array_pop\\(", "\\1(void) array_pop(", lines)
  write_lf(lines, file.path(pkg_src, f))
}

abi_line <- grep("^#define LANGUAGE_VERSION", readLines(file.path(src, "parser.c")), value = TRUE)
abi <- as.integer(sub("^#define LANGUAGE_VERSION\\s+", "", abi_line))
if (is.na(abi) || abi > 14L) {
  stop("Grammar ABI ", abi, " is not supported by the CRAN treesitter package.")
}

abi_r <- c(
  "# This file is generated by `tools/vendor-grammar.R`, do not modify by hand.",
  "",
  "# ABI version that the vendored `parser.c` was generated with, and the",
  "# upstream tree-sitter-python version it came from.",
  sprintf("grammar_abi <- function() %dL", abi),
  sprintf("grammar_version <- function() \"%s\"", version)
)
write_lf(abi_r, file.path(root, "packages", "pyport", "R", "grammar-abi.R"))

invisible(file.copy(
  file.path(tmp, sprintf("tree-sitter-python-%s", version), "LICENSE"),
  file.path(root, "packages", "pyport", "inst", "LICENSE.tree-sitter-python"),
  overwrite = TRUE
))

message("Vendored tree-sitter-python ", version, " (ABI ", abi, ").")
